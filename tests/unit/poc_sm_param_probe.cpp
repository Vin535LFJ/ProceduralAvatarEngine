// PoC-SM round 2 (AL-6): parameter differential evidence probe.
// Writes the complete single-parameter matrix to evidence/poc-sm.

#include "poc_sm_param_diff.h"

#include <cstdio>
#include <cstring>
#include <string>

using namespace pae;
using namespace pae::shape;
using namespace pae::shape::v2;
using namespace pae::shape::v2::param_diff;

namespace {

std::string outDir = "evidence/poc-sm/round-2";

bool ensureDir(const std::string& path) {
    const std::string cmd = "mkdir -p \"" + path + "\"";
    return std::system(cmd.c_str()) == 0;
}

const char* bandName(int i) {
    switch (i) {
        case Band::Pelvis: return "pelvis";
        case Band::Abdomen: return "abdomen";
        case Band::Thorax: return "thorax";
        case Band::ShoulderGirdle: return "shoulder-girdle";
    }
    return "?";
}

} // namespace

int main(int argc, char** argv) {
    for (int i = 1; i < argc; ++i) {
        if (std::strcmp(argv[i], "--out") == 0 && i + 1 < argc) outDir = argv[++i];
    }
    if (!ensureDir(outDir)) return 2;

    const std::vector<ShapeResult> shapes = scanShapeParameters();
    const std::vector<ProportionResult> props = scanProportions();

    const std::string csv = outDir + "/al6-shape-parameter-delta.csv";
    std::FILE* f = std::fopen(csv.c_str(), "wb");
    if (f == nullptr) return 2;
    std::fprintf(f, "name,declared_status,applied_value,max_delta_mm,mean_delta_mm,rms_delta_mm,"
                    "pelvis_band_max_mm,abdomen_band_max_mm,thorax_band_max_mm,"
                    "shoulder_band_max_mm,moves_geometry\n");
    for (const ShapeResult& r : shapes) {
        const Delta& d = r.delta;
        std::fprintf(f, "%s,%s,%s,%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%s\n",
                     r.name.c_str(), r.declaredStatus.c_str(), r.usedValue.c_str(),
                     d.maxM * 1000.0, d.meanM * 1000.0, d.rmsM * 1000.0,
                     d.bandMaxM[0] * 1000.0, d.bandMaxM[1] * 1000.0,
                     d.bandMaxM[2] * 1000.0, d.bandMaxM[3] * 1000.0,
                     r.actuallyMovesGeometry ? "yes" : "no");
    }
    std::fclose(f);

    const std::string pcsv = outDir + "/al6-proportion-delta.csv";
    f = std::fopen(pcsv.c_str(), "wb");
    if (f == nullptr) return 2;
    std::fprintf(f, "field,applied_scale,max_delta_mm,mean_delta_mm,rms_delta_mm,"
                    "pelvis_band_max_mm,abdomen_band_max_mm,thorax_band_max_mm,"
                    "shoulder_band_max_mm,moves_geometry\n");
    for (const ProportionResult& r : props) {
        const Delta& d = r.delta;
        std::fprintf(f, "%s,%.3f,%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%s\n",
                     r.field.c_str(), r.appliedScale,
                     d.maxM * 1000.0, d.meanM * 1000.0, d.rmsM * 1000.0,
                     d.bandMaxM[0] * 1000.0, d.bandMaxM[1] * 1000.0,
                     d.bandMaxM[2] * 1000.0, d.bandMaxM[3] * 1000.0,
                     r.actuallyMovesGeometry ? "yes" : "no");
    }
    std::fclose(f);

    const std::string md = outDir + "/al6-parameter-differential-report.md";
    f = std::fopen(md.c_str(), "wb");
    if (f == nullptr) return 2;
    std::fprintf(f, "# AL-6 — complete single-parameter differential test\n\n");
    std::fprintf(f, "> Generated by `poc_sm_param_probe` in round 2. One parameter at a time;\n");
    std::fprintf(f, "> baseline = default CharacterDefinition, 26 rings x 32 segments.\n");
    std::fprintf(f, "> Vertex deltas are mm at identical vertex ids. Region bands are a\n");
    std::fprintf(f, "> HEIGHT PROXY (no placed anatomical landmarks exist in PoC-SM).\n\n");

    std::fprintf(f, "## 1. ShapeParameters (all 10 declared parameters)\n\n");
    std::fprintf(f, "| Parameter | Declared | Applied | max (mm) | mean (mm) | RMS (mm) | Dominant band | Moves mesh |\n");
    std::fprintf(f, "|---|---|---:|---:|---:|---:|---|:--:|\n");
    for (const ShapeResult& r : shapes) {
        int dominant = 0;
        for (int i = 1; i < BandCount; ++i) {
            if (r.delta.bandMaxM[i] > r.delta.bandMaxM[static_cast<size_t>(dominant)]) dominant = i;
        }
        std::fprintf(f, "| `%s` | %s | %s | %.4f | %.4f | %.4f | %s | %s |\n",
                     r.name.c_str(), r.declaredStatus.c_str(), r.usedValue.c_str(),
                     r.delta.maxM * 1000.0, r.delta.meanM * 1000.0, r.delta.rmsM * 1000.0,
                     bandName(dominant), r.actuallyMovesGeometry ? "YES" : "no");
    }
    std::fprintf(f, "\nRaw CSV: `%s`\n\n", csv.c_str());

    std::fprintf(f, "## 2. ProportionProfile (all consumed and declared fields)\n\n");
    std::fprintf(f, "| Field | Scale applied | max (mm) | mean (mm) | RMS (mm) | Moves mesh |\n");
    std::fprintf(f, "|---|---:|---:|---:|---:|:--:|\n");
    for (const ProportionResult& r : props) {
        std::fprintf(f, "| `%s` | %.2f | %.4f | %.4f | %.4f | %s |\n",
                     r.field.c_str(), r.appliedScale,
                     r.delta.maxM * 1000.0, r.delta.meanM * 1000.0, r.delta.rmsM * 1000.0,
                     r.actuallyMovesGeometry ? "YES" : "no");
    }
    std::fprintf(f, "\nRaw CSV: `%s`\n\n", pcsv.c_str());

    std::fprintf(f, "## 3. Honest status of the measurements\n\n");
    std::fprintf(f, "- `spine-curve` is `DeclaredOnly` and produces an exactly zero mesh delta.\n");
    std::fprintf(f, "- `shoulderBreadthRatio`, `biacromialRatio`, `abdominalDepthRatio` and\n");
    std::fprintf(f, "  `headHeightRatio` carry measurement-derived numbers but are NOT read by\n");
    std::fprintf(f, "  the generator; their deltas are zero. No claim of use is made.\n");
    std::fprintf(f, "- The shoulder girdle currently derives its width from `chestHalfWidth *\n");
    std::fprintf(f, "  girdleMass`, NOT from the measured biacromial breadth. Mapping those\n");
    std::fprintf(f, "  fields requires an owner-approved anatomical decision.\n\n");
    std::fclose(f);

    std::printf("shape parameters: %zu, proportions: %zu\n", shapes.size(), props.size());
    std::printf("report: %s\n", md.c_str());
    return 0;
}

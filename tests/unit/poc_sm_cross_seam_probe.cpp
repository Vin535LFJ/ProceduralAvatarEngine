// PoC-SM round 2: cross-boundary seam experiment probe.
//
// Writes the measurement matrix into evidence/poc-sm. This is an EXPERIMENT:
// it compares the signed OQ-03 ring-band statistic with an independent
// cross-boundary statistic on known synthetic folds. It makes no Gate
// judgement and does not change any signed decision.

#include "poc_sm_cross_seam_fixture.h"
#include "procedural/shape/v2/CrossBoundarySeamAudit.h"

#include <cstdio>
#include <cstring>
#include <string>
#include <vector>

using namespace pae;
using namespace pae::shape;
using namespace pae::shape::v2;
using namespace pae::shape::v2::cross_seam_fixture;

namespace {

std::string outDir = "evidence/poc-sm/round-2";

bool ensureDir(const std::string& path) {
    const std::string cmd = "mkdir -p \"" + path + "\"";
    return std::system(cmd.c_str()) == 0;
}

struct Row {
    int segments = 0;
    int rows = 0;
    float fold = 0.0f;
    double legacyMaxDeg = 0.0;
    double legacyMeanDeg = 0.0;
    CrossBoundarySeamMeasurement cross;
};

} // namespace

int main(int argc, char** argv) {
    for (int i = 1; i < argc; ++i) {
        if (std::strcmp(argv[i], "--out") == 0 && i + 1 < argc) {
            outDir = argv[++i];
        }
    }
    if (!ensureDir(outDir)) {
        std::fprintf(stderr, "cannot create %s\n", outDir.c_str());
        return 2;
    }

    const int segmentCounts[] = {32, 64, 96, 128};
    const float folds[] = {0.0f, 5.0f, 15.0f, 30.0f};
    std::vector<Row> rows;
    for (int segments : segmentCounts) {
        for (float fold : folds) {
            const FoldedSeam f = makeFoldedSeam(segments, 4, fold);
            Row row;
            row.segments = segments;
            row.rows = 4;
            row.fold = fold;
            const SeamMeasurement legacy =
                measureShoulderRootSeam(f.combined, f.quads, f.crops);
            row.legacyMaxDeg = legacy.maxDeg;
            row.legacyMeanDeg = legacy.meanDeg;
            row.cross = measureCrossBoundarySeam(f.lower, f.upper);
            rows.push_back(row);
        }
    }

    // Edge cases: must be NOT APPLICABLE, never PASS.
    const FoldedSeam flipped = makeFoldedSeam(64, 4, 10.0f, true);
    const CrossBoundarySeamMeasurement mFlip = measureCrossBoundarySeam(flipped.lower, flipped.upper);
    const FoldedSeam shifted = makeFoldedSeam(64, 4, 10.0f, false, 0.5f);
    const CrossBoundarySeamMeasurement mShift = measureCrossBoundarySeam(shifted.lower, shifted.upper);
    const FoldedSeam normal = makeFoldedSeam(32, 4, 10.0f);
    SeamPatch missing;
    const CrossBoundarySeamMeasurement mMissing = measureCrossBoundarySeam(normal.lower, missing);

    const std::string csvPath = outDir + "/cross-boundary-seam-matrix.csv";
    std::FILE* csv = std::fopen(csvPath.c_str(), "wb");
    if (csv == nullptr) {
        std::fprintf(stderr, "cannot write %s\n", csvPath.c_str());
        return 2;
    }
    std::fprintf(csv, "segments,rows,known_fold_deg,legacy_ring_max_deg,legacy_ring_mean_deg,"
                      "cross_applicability,cross_max_deg,cross_mean_deg,cross_p95_deg,"
                      "position_error_max_m,winding_ok,angle_samples\n");
    for (const Row& row : rows) {
        const CrossBoundarySeamMeasurement& m = row.cross;
        std::fprintf(csv, "%d,%d,%.1f,%.6f,%.6f,%s,%.6f,%.6f,%.6f,%.9f,%s,%d\n",
                     row.segments, row.rows, row.fold, row.legacyMaxDeg, row.legacyMeanDeg,
                     crossSeamApplicabilityName(m.applicability), m.maxDeg, m.meanDeg, m.p95Deg,
                     m.positionErrorMaxM, m.windingVerified ? "yes" : "no", m.usableAngleSamples);
    }
    std::fclose(csv);

    const std::string mdPath = outDir + "/cross-boundary-seam-report.md";
    std::FILE* f = std::fopen(mdPath.c_str(), "wb");
    if (f == nullptr) {
        std::fprintf(stderr, "cannot write %s\n", mdPath.c_str());
        return 2;
    }
    std::fprintf(f, "# Cross-boundary seam audit — EXPERIMENT (no Gate decision)\n\n");
    std::fprintf(f, "> Generated by `poc_sm_cross_seam_probe` in round 2. The signed OQ-03\n");
    std::fprintf(f, "> ring-band definition is unchanged; `measureShoulderRootSeam()` is untouched.\n");
    std::fprintf(f, "> No threshold has been approved for the new statistic. NOT APPLICABLE is\n");
    std::fprintf(f, "> never PASS.\n\n");

    std::fprintf(f, "## 1. Synthetic construction\n\n");
    std::fprintf(f, "Two patches meet on a circular ring at y=0, radius 0.50 m, with outward\n");
    std::fprintf(f, "triangle winding. The upper patch is a cone of slope tan(fold); the true\n");
    std::fprintf(f, "cross-boundary dihedral is therefore the prescribed fold. Both normals are\n");
    std::fprintf(f, "read from the mesh's own triangles and index buffer.\n\n");

    std::fprintf(f, "## 2. Measurement matrix\n\n");
    std::fprintf(f, "| Segments | Rows | Known fold | Legacy ring max (deg) | Cross max (deg) | Cross mean | Cross p95 | Applicability | Samples |\n");
    std::fprintf(f, "|---:|---:|---:|---:|---:|---:|---:|:--:|---:|\n");
    for (const Row& row : rows) {
        const CrossBoundarySeamMeasurement& m = row.cross;
        std::fprintf(f, "| %d | %d | %.0f deg | %.4f | %.4f | %.4f | %.4f | %s | %d |\n",
                     row.segments, row.rows, row.fold, row.legacyMaxDeg, m.maxDeg,
                     m.meanDeg, m.p95Deg, crossSeamApplicabilityName(m.applicability),
                     m.usableAngleSamples);
    }
    std::fprintf(f, "\nRaw CSV: `%s`\n\n", csvPath.c_str());

    std::fprintf(f, "## 3. Negative controls\n\n");
    std::fprintf(f, "| Case | Applicability | Winding verified | Unmatched | Position error max (m) | Usable samples |\n");
    std::fprintf(f, "|---|---|:--:|---:|---:|---:|\n");
    std::fprintf(f, "| Reversed upper winding | %s | %s | %d | %.9f | %d |\n",
                 crossSeamApplicabilityName(mFlip.applicability),
                 mFlip.windingVerified ? "yes" : "no", mFlip.unmatchedVertices,
                 mFlip.positionErrorMaxM, mFlip.usableAngleSamples);
    std::fprintf(f, "| Half-segment boundary offset | %s | %s | %d | %.9f | %d |\n",
                 crossSeamApplicabilityName(mShift.applicability),
                 mShift.windingVerified ? "yes" : "no", mShift.unmatchedVertices,
                 mShift.positionErrorMaxM, mShift.usableAngleSamples);
    std::fprintf(f, "| Missing second patch | %s | %s | %d | %.9f | %d |\n",
                 crossSeamApplicabilityName(mMissing.applicability),
                 mMissing.windingVerified ? "yes" : "no", mMissing.unmatchedVertices,
                 mMissing.positionErrorMaxM, mMissing.usableAngleSamples);
    std::fprintf(f, "\n");

    std::fprintf(f, "## 4. Technical interpretation (not a decision)\n\n");
    std::fprintf(f, "- The legacy statistic changes with 360/segments on a perfect fold and is\n");
    std::fprintf(f, "  therefore not a stable estimator of the cross-boundary dihedral.\n");
    std::fprintf(f, "- The cross-boundary statistic reads the prescribed fold at every sampled\n");
    std::fprintf(f, "  segment count and density in this synthetic construction.\n");
    std::fprintf(f, "- Whether this faithfully expresses the original Geometry Mesh Contract\n");
    std::fprintf(f, "  semantic ('normal angle on both sides of a seam') remains an OWNER decision.\n");
    std::fprintf(f, "- The current v2 shared envelope is ONE continuous surface with no second\n");
    std::fprintf(f, "  component at the crop ring, so on the real mesh this experiment is\n");
    std::fprintf(f, "  NOT APPLICABLE — which is not PASS.\n\n");
    std::fclose(f);

    std::printf("cross-seam rows: %zu\n", rows.size());
    std::printf("report: %s\n", mdPath.c_str());
    std::printf("csv: %s\n", csvPath.c_str());
    return 0;
}

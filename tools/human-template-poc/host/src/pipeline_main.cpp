int main(int argc, char** argv) {
    std::string dataDir, repoRoot, outDir, commit = kCommitDefault, archive;
    bool images = true;
    for (int i = 1; i + 1 < argc; ++i) {
        const std::string k = argv[i], v = argv[i + 1];
        if (k == "--data") dataDir = v;
        else if (k == "--repo") repoRoot = v;
        else if (k == "--out") outDir = v;
        else if (k == "--commit") commit = v;
        else if (k == "--archive") archive = v;
        else if (k == "--no-images") images = false;
    }
    if (dataDir.empty() || repoRoot.empty() || outDir.empty()) {
        std::printf("usage: pae_ht_pipeline --data <dir> --repo <dir> --out <dir> [--commit sha] [--archive zip] [--no-images]\n");
        return 2;
    }
    const std::string reportDir = outDir + "/report", imageDir = outDir + "/images", templateDir = outDir + "/template";
    const std::string provDir = outDir + "/provenance", exportDir = outDir + "/export";
    for (const std::string& d : {reportDir, imageDir, templateDir, provDir, exportDir})
        if (!makeDirs(d)) {
            std::printf("cannot create %s\n", d.c_str());
            return 2;
        }
    const double tStart = nowMs();
    say(fmt("[run] PAE human-template host-only proof | %s | commit %s", utcNow().c_str(), commit.c_str()));

    // ------------------------------------------------------ 1. load
    ProofContext c;
    std::string error;
    const double tLoad0 = nowMs();
    if (!c.load(dataDir, repoRoot, error)) {
        say("[error] " + error);
        return 1;
    }
    const double loadMs = nowMs() - tLoad0;
    for (const std::string& l : c.log) say(l);
    const PolyMesh& body = c.body;
    const std::vector<D3>& base = body.pos;

    // ------------------------------------------------------ 2. provenance
    std::string manifest = "# Asset manifest (generated by pae_ht_pipeline)\n\n";
    manifest += fmt("- Source repository: https://github.com/makehumancommunity/makehuman\n- Pinned commit: `%s`\n- Generated: %s\n\n",
                    commit.c_str(), utcNow().c_str());
    if (!archive.empty()) manifest += fmt("- Archive `%s` sha256: `%s`\n\n", fileNameOf(archive).c_str(), sha256HexFile(archive).c_str());
    manifest += "| File (repo-relative) | Role | Bytes | SHA-256 | License | Basis |\n|---|---|---:|---|---|---|\n";
    std::vector<SourceFile> files;
    auto addFile = [&](const std::string& rel, const std::string& role, const std::string& license, const std::string& basis) {
        const std::string path = repoPath(c, rel);
        std::vector<uint8_t> bytes;
        if (!readFileBytes(path, bytes)) {
            say("[error] missing provenance file " + rel);
            return;
        }
        SourceFile f;
        f.path = "makehuman/" + rel;
        f.sha256 = sha256Hex(bytes);
        f.sizeBytes = static_cast<long>(bytes.size());
        f.role = role;
        f.license = license;
        f.basis = basis;
        files.push_back(f);
        manifest += fmt("| `%s` | %s | %ld | `%s` | %s | %s |\n", ("makehuman/" + rel).c_str(), role.c_str(), f.sizeBytes,
                        f.sha256.c_str(), license.c_str(), basis.c_str());
    };
    const std::string cc0Basis = "LICENSE.md section C (bundled assets are CC0); file header states CC0";
    addFile("LICENSE.md", "license-text", "CC0-1.0 (assets) / AGPL (code, unused)", "root license file");
    addFile("LICENSE.ASSETS.md", "license-text", "CC0-1.0", "full CC0 legal text");
    addFile("LICENSE.CODE.md", "license-text", "AGPL-3.0 (NOT used by PAE)", "shown for completeness; no code copied");
    addFile("makehuman/data/3dobjs/base.obj", "base-mesh", "CC0-1.0", cc0Basis);
    // Rig and weights are NOT license-verified: the CC0 claim rests on an in-file string only and
    // LICENSE.md does not enumerate these two files. The owner has not confirmed them, so the label
    // stays PENDING_CONFIRMATION (host-only evaluation use, not cleared for redistribution).
    const std::string pending = "PENDING_CONFIRMATION (CC0 declared in file only)";
    addFile("makehuman/data/rigs/default.mhskel", "rig-definition", pending, "NOT VERIFIED: no CC0 header; JSON `license: CC0` is the only claim; not individually enumerated in LICENSE.md; owner confirmation outstanding");
    addFile("makehuman/data/rigs/default_weights.mhw", "skin-weights", pending, "NOT VERIFIED: JSON `license: CC0` is the only claim; not individually enumerated in LICENSE.md; owner confirmation outstanding");
    for (const ShapeParam& p : c.params) {
        for (const std::string& rel : p.incrFiles) addFile("makehuman/data/" + rel, "shape-target [" + p.key + " +]", "CC0-1.0", cc0Basis);
        for (const std::string& rel : p.decrFiles) addFile("makehuman/data/" + rel, "shape-target [" + p.key + " -]", "CC0-1.0", cc0Basis);
    }
    writeFile(provDir + "/asset-manifest.md", manifest);
    say(fmt("[provenance] %zu files hashed -> %s/provenance/asset-manifest.md", files.size(), outDir.c_str()));

    // ------------------------------------------------------ 3. topology audit
    const TopologyAudit a = auditTopology(body, c.topo);
    std::string topoMd = "# Base human topology audit (generated)\n\nSource: `makehuman/data/3dobjs/base.obj` @ `" + std::string(commit) +
                         "`  \nsha256: `" + c.obj.sourceSha256 + "`\n\nBody = OBJ group `body`. Helper and joint groups are excluded from the skin.\n\n";
    topoMd += "| Item | Value |\n|---|---|\n";
    auto row = [&](const std::string& k, const std::string& v) { topoMd += "| " + k + " | " + v + " |\n"; };
    row("Vertices (stable ids 0..N-1 = OBJ `v` order)", std::to_string(a.vertexCount));
    row("Faces / quads / tris / n-gons", fmt("%ld / %ld / %ld / %ld", a.faceCount, a.quadCount, a.triCount, a.ngonCount));
    row("Edges", std::to_string(a.edgeCount));
    row("Euler characteristic V-E+F", std::to_string(a.eulerChi));
    row("Connected components", std::to_string(a.componentCount));
    row("Boundary edges / boundary loops", fmt("%ld / %d", a.boundaryEdgeCount, a.boundaryLoopCount));
    row("Non-manifold edges", std::to_string(a.nonManifoldEdgeCount));
    row("Inconsistent-winding edges", std::to_string(a.inconsistentWindingEdgeCount));
    row("Duplicate / degenerate / zero-area faces", fmt("%ld / %ld / %ld", a.duplicateFaceCount, a.degenerateFaceCount, a.zeroAreaFaceCount));
    row("Isolated vertices", std::to_string(a.isolatedVertexCount));
    row("Outward winding (signed volume > 0)", a.outwardWinding ? "yes" : "no");
    row("Vertex valence min / max", fmt("%d / %d", a.valenceMin, a.valenceMax));
    std::string hist;
    for (const auto& v : a.valenceHistogram) hist += fmt("%d:%ld ", v.first, v.second);
    row("Valence histogram", hist);
    row("Edge length min / p50 / max (m)", fmt("%.4f / %.4f / %.4f", a.edgeLength.min, a.edgeLength.p50, a.edgeLength.max));
    row("Quad corner angle min / p01 / median (deg)", fmt("%.2f / %.2f / %.2f", a.minCornerAngleDeg.min, a.minCornerAngleDeg.p01, a.minCornerAngleDeg.p50));
    row("Triangle min angle (shorter-diagonal split) min / p01 (deg)", fmt("%.2f / %.2f", a.triangleMinAngleDeg.min, a.triangleMinAngleDeg.p01));
    row("Triangle aspect ratio (1 = equilateral) mean / p99 / max", fmt("%.2f / %.2f / %.2f", a.aspectRatio.mean, a.aspectRatio.p99, a.aspectRatio.max));
    row("Dihedral angle max / edges > 60 deg / > 90 deg", fmt("%.1f / %ld / %ld", a.dihedralDeg.max, a.dihedralOver60, a.dihedralOver90));
    row("UV: vt count, faces with UV, seam edges", fmt("%d / %ld / %ld", static_cast<int>(body.uv.size()),
        std::count_if(body.faces.begin(), body.faces.end(), [](const PolyFace& f) { return std::all_of(f.vt.begin(), f.vt.end(), [](int t) { return t >= 0; }); }),
        a.uvSeamEdgeCount));
    row("Render-mesh vertices before triangulation (unique v+vt pairs)", std::to_string(a.uniqueUvVertexPairCount));
    row("Triangles after fan triangulation", std::to_string(a.triangulatedCount));
    row("Material regions (`usemtl`)", a.materialFaceCount ? a.materialNames : "none in the OBJ");
    row("Surface area (m^2) / signed volume (L)", fmt("%.3f / %.2f", a.surfaceArea, a.signedVolume * 1000.0));
    topoMd += "\nNot measured by this tool: self-intersection, non-manifold vertices (bow-tie), curvature, local refinement. See the report for the manual region review.\n";
    writeFile(reportDir + "/topology-audit.md", topoMd);
    const GroupCensus census = censusGroups(c.obj);
    say(fmt("[topology] V=%ld F=%ld(quads) E=%ld chi=%ld comps=%d boundary=%ld nonmanifold=%ld windingConflicts=%ld uvSeams=%ld outward=%d",
            a.vertexCount, a.faceCount, a.edgeCount, a.eulerChi, a.componentCount, a.boundaryEdgeCount, a.nonManifoldEdgeCount,
            a.inconsistentWindingEdgeCount, a.uvSeamEdgeCount, a.outwardWinding ? 1 : 0));
    say(fmt("[topology] valence %d..%d edge %.4f..%.4f m cornerAngle min %.2f deg aspect max %.2f dihedral max %.1f deg",
            a.valenceMin, a.valenceMax, a.edgeLength.min, a.edgeLength.max, a.minCornerAngleDeg.min, a.aspectRatio.max, a.dihedralDeg.max));
    say(fmt("[helpers] joint groups=%d (%ld faces) other helper groups=%d (%ld faces): %s", census.jointGroups, census.jointFaces,
            census.otherHelperGroups, census.otherHelperFaces, census.otherHelperNames.c_str()));

    // ------------------------------------------------------ 4. shape targets
    const Measures baseM = measureBody(base, c.regions, c.rigDeform);
    struct ParamResult {
        const ShapeParam* p;
        std::vector<double> meanI, meanD;   // mean |displacement| per region (m)
        double helperShareI = 0.0;
        Measures mI, mD;
        double dI = 0, dD = 0;
        int measure = 0;
        DeformationQuality qI, qD;
        double targetMs = 0;
    };
    std::vector<ParamResult> results;
    const double tTargets = nowMs();
    for (const ShapeParam& p : c.params) {
        ParamResult r;
        r.p = &p;
        const double t0 = nowMs();
        r.meanI = regionMeanDisplacement(c.regions, p.incr.vertex, p.incr.delta);
        r.meanD = regionMeanDisplacement(c.regions, p.decr.vertex, p.decr.delta);
        regionDisplacementShare(c.regions, p.incr.vertex, p.incr.delta, &r.helperShareI);
        std::vector<D3> inc, dec;
        applyToBody(c, {{&p.incr, 1.0}}, inc);
        applyToBody(c, {{&p.decr, 1.0}}, dec);
        r.mI = measureBody(inc, c.regions, c.rigDeform);
        r.mD = measureBody(dec, c.regions, c.rigDeform);
        r.qI = compareSurfaces(body, inc, c.topo);
        r.qD = compareSurfaces(body, dec, c.topo);
        r.targetMs = nowMs() - t0;
        r.measure = p.key == "shoulderWidth" ? 0 : p.key == "ribcageWidth" ? 1 : p.key == "chestDepth" ? 2 : p.key == "waistWidth" ? 3
                   : p.key == "hipWidth" ? 4 : p.key == "stature" ? 5 : -1;
        auto val = [&](const Measures& m) {
            switch (r.measure) {
                case 0: return m.bideltoidWidth;
                case 1: return m.chestWidth;
                case 2: return m.chestDepth;
                case 3: return m.waistWidth;
                case 4: return m.hipWidth;
                default: return m.stature;
            }
        };
        r.dI = val(r.mI) - val(baseM);
        r.dD = val(r.mD) - val(baseM);
        results.push_back(r);
    }
    const double targetTotalMs = nowMs() - tTargets;
    say(fmt("[targets] %zu parameters applied to the full OBJ (body + helpers) in %.1f ms total", results.size(), targetTotalMs));

    std::string shapeMd = "# Shape target application (generated)\n\n";
    shapeMd += "Formula: `V = V0 + sum(alpha_i * dV_i)`, applied to the WHOLE OBJ (body + helper + joint vertices), because the targets also encode helper motion and the rig's joint centres are means of joint-cube vertices. All values in metres on the pinned `base.obj` body.\n\n";
    shapeMd += "Measurement planes are PAE's own definition for this proof (not MakeHuman's): bideltoid = shoulder-joint height - 2.5 % stature over shoulder-girdle + upper-arm vertices; chest = 72 % stature over thorax vertices; waist = 60 % stature over abdomen vertices; hip = hip-joint height over pelvis + thigh vertices; band half-width 1.5 % stature. Region labels are heuristic (nearest bone with radius normalisation; trunk zones by height).\n\n";
    shapeMd += "| Parameter | Target files (+ / -) | Rows | Mean displacement per region at +1.0 (mm, top 5) | Share of |displacement| on helper geometry | Named measure: base / +1 / -1 | Delta (+ / -) | Stature delta (+ / -) | Folded faces (+ / -) | Edge stretch p99 (+ / -) | Volume ratio (+ / -) |\n|---|---|---:|---|---:|---|---|---|---|---|---|\n";
    const char* names[] = {"bideltoid width", "chest width", "chest depth", "waist width", "hip width", "stature"};
    for (const ParamResult& r : results) {
        auto files = [](const std::vector<std::string>& v) {
            std::string s;
            for (const std::string& f : v) s += (s.empty() ? "" : " + ") + f.substr(f.find_last_of('/') + 1);
            return s;
        };
        std::vector<int> bySize(kRegionCount);
        for (int i = 0; i < kRegionCount; ++i) bySize[static_cast<size_t>(i)] = i;
        std::sort(bySize.begin(), bySize.end(), [&](int x, int y) { return r.meanI[static_cast<size_t>(x)] > r.meanI[static_cast<size_t>(y)]; });
        std::string means;
        for (size_t i = 0; i < 5 && i < bySize.size(); ++i)
            if (r.meanI[static_cast<size_t>(bySize[i])] > 1e-6)
                means += fmt("%s %.1f, ", regionName(static_cast<Region>(bySize[i])), r.meanI[static_cast<size_t>(bySize[i])] * 1000.0);
        if (!means.empty()) means.pop_back(), means.pop_back();
        // A parameter without a named measurement (armShape, legShape, headShape)
        // must print "-" for it; falling through to slot 0 used to label the
        // stature value as "bideltoid width".
        const bool hasMeasure = r.measure >= 0;
        const char* measureName = hasMeasure ? names[r.measure] : "no named measure";
        auto val = [&](const Measures& m) {
            if (!hasMeasure) return 0.0;
            switch (r.measure) {
                case 0: return m.bideltoidWidth;
                case 1: return m.chestWidth;
                case 2: return m.chestDepth;
                case 3: return m.waistWidth;
                case 4: return m.hipWidth;
                default: return m.stature;
            }
        };
        const std::string measureCell = hasMeasure
            ? fmt("%s: %.4f / %.4f / %.4f", measureName, val(baseM), val(r.mI), val(r.mD)) : std::string("-");
        const std::string deltaCell = hasMeasure ? fmt("%+.4f / %+.4f", r.dI, r.dD) : std::string("-");
        shapeMd += fmt("| %s (`%s`) | %s / %s | %ld | %s | %.1f %% | %s | %s | %+.4f / %+.4f | %ld / %ld | %.3f / %.3f | %.4f / %.4f |\n",
                       r.p->key.c_str(), measureName, files(r.p->incrFiles).c_str(), files(r.p->decrFiles).c_str(), r.p->incr.dataRows,
                       means.c_str(), r.helperShareI * 100.0, measureCell.c_str(), deltaCell.c_str(),
                       r.mI.stature - baseM.stature, r.mD.stature - baseM.stature, r.qI.flippedFaces, r.qD.flippedFaces, r.qI.edgeRatioP99,
                       r.qD.edgeRatioP99, r.qI.volumeRatio, r.qD.volumeRatio);
        say(fmt("[target] %-13s %-17s base %.4f  +1 %+.4f  -1 %+.4f | stature %+.4f/%+.4f | mean|disp|: %s | helper share %.1f%% | flips %ld/%ld",
                r.p->key.c_str(), measureName, val(baseM), r.dI, r.dD, r.mI.stature - baseM.stature, r.mD.stature - baseM.stature,
                means.c_str(), r.helperShareI * 100.0, r.qI.flippedFaces, r.qD.flippedFaces));
    }
    // Combination of the eight local parameters (the standalone macro height
    // target is excluded: it is authored for use inside a macro combination).
    std::vector<std::pair<const ShapeTarget*, double>> allInc, allInc15;
    for (const ShapeParam& p : c.params) {
        if (p.key == "stature") continue;
        allInc.push_back({&p.incr, 1.0});
        allInc15.push_back({&p.incr, 1.5});
    }
    std::vector<D3> combined, overshoot;
    applyToBody(c, allInc, combined);
    applyToBody(c, allInc15, overshoot);
    const DeformationQuality qAll = compareSurfaces(body, combined, c.topo), qOver = compareSurfaces(body, overshoot, c.topo);
    const Measures mAll = measureBody(combined, c.regions, c.rigDeform), mOver = measureBody(overshoot, c.regions, c.rigDeform);
    shapeMd += fmt("\nCombined (the eight local parameters at +1.0): stature %.4f, bideltoid %.4f, chest %.4f x %.4f, waist %.4f, hip %.4f; folded faces %ld, edge stretch p99 %.3f, volume ratio %.4f.  \n\nOvershoot (the same eight at +1.5, outside the authored 0..1 range): bideltoid %.4f, chest %.4f x %.4f, waist %.4f, hip %.4f; folded faces %ld, edge stretch p99 %.3f, volume ratio %.4f.  \n",
                   mAll.stature, mAll.bideltoidWidth, mAll.chestWidth, mAll.chestDepth, mAll.waistWidth, mAll.hipWidth, qAll.flippedFaces,
                   qAll.edgeRatioP99, qAll.volumeRatio, mOver.bideltoidWidth, mOver.chestWidth, mOver.chestDepth, mOver.waistWidth,
                   mOver.hipWidth, qOver.flippedFaces, qOver.edgeRatioP99, qOver.volumeRatio);
    shapeMd += "\nNot verified: self-intersection after targets, parameter ranges as authored by MakeHuman (sliders), targets beyond +/-1.0, macro combinations (gender / age / race / muscle / weight), faces and expressions.\n";
    say(fmt("[target] eight local at +1.0: flips %ld edgeP99 %.3f vol %.4f | at +1.5: flips %ld edgeP99 %.3f vol %.4f", qAll.flippedFaces,
            qAll.edgeRatioP99, qAll.volumeRatio, qOver.flippedFaces, qOver.edgeRatioP99, qOver.volumeRatio));
    writeFile(reportDir + "/shape-targets.md", shapeMd);

    // ------------------------------------------------------ 5. rig census
    std::string rigMd = "# Rig V2 (generated)\n\nSource: `makehuman/data/rigs/default.mhskel` (`" + c.rigFile.name + "`, format v" +
                        std::to_string(c.rigFile.version) + ", license declared in file: " + c.rigFile.license +
                        "; NOT VERIFIED - the file is not enumerated in LICENSE.md, status PENDING owner confirmation).\n\n";
    rigMd += fmt("Source bones: %zu. PAE role census (PAE's own name-based classification):\n\n| PAE role | Bones | In deform rig | In core rig |\n|---|---:|---|---|\n", c.rigFile.bones.size());
    for (int r = 0; r < static_cast<int>(Role::Count); ++r) {
        long n = 0, nd = 0, nc = 0;
        for (const RigFileBone& b : c.rigFile.bones) n += roleOfBoneName(b.name) == static_cast<Role>(r) ? 1 : 0;
        for (const RigBone& b : c.rigDeform.bones) nd += b.role == static_cast<Role>(r) ? 1 : 0;
        for (const RigBone& b : c.rigCore.bones) nc += b.role == static_cast<Role>(r) ? 1 : 0;
        if (n) rigMd += fmt("| %s | %ld | %s | %s |\n", roleName(static_cast<Role>(r)), n, nd ? std::to_string(nd).c_str() : "-", nc ? std::to_string(nc).c_str() : "-");
    }
    rigMd += fmt("\n| Variant | Bones | Notes |\n|---|---:|---|\n| PAEHumanRigV2-deform | %zu | every non-facial source bone; fingers (3 x 5 per side), toes, twist bones (upperarm02, lowerarm02, upperleg02, lowerleg02), clavicle + shoulder, 5 spine, 3 neck |\n| PAEHumanRigV2-core | %zu | root, spine01/03/05, neck01, head, clavicle, upperarm01, lowerarm01, wrist, upperleg01, lowerleg01, foot per side; no digits, no twist split |\n| LegacyRigV1 (production, untouched) | 22 | Root, Hips, Spine, Chest, Neck, Head, L/R Shoulder, UpperArm, LowerArm, Hand, UpperLeg, LowerLeg, Foot, Toe |\n\n",
                    c.rigDeform.bones.size(), c.rigCore.bones.size());
    int withPlane = 0;
    for (const RigBone& b : c.rigDeform.bones) withPlane += b.planeNormal.lengthSq() > 0.5 ? 1 : 0;
    rigMd += fmt("Bones with a roll-reference plane normal: %d of %zu (deform rig). Bone head/tail come from the rig's joint definitions resolved as the mean of the base.obj joint-helper cube vertices on the CURRENT surface, so the rig follows every shape change.\n", withPlane, c.rigDeform.bones.size());
    writeFile(reportDir + "/rig.md", rigMd);
    say(fmt("[rig] source %zu bones -> deform %zu, core %zu; %d roll planes", c.rigFile.bones.size(), c.rigDeform.bones.size(), c.rigCore.bones.size(), withPlane));

    // ------------------------------------------------------ 6. weights
    SkinWeights mh, dist, heat;
    const double tMh0 = nowMs();
    if (!readMhWeights(dataPath(c, "rigs/default_weights.mhw"), c.rigDeform, static_cast<int>(c.full.size()), mh, error, &c.rigFile, &c.full)) {
        say("[error] " + error);
        return 1;
    }
    mh.generationMs = nowMs() - tMh0;
    dist = generateDistanceWeights(body, c.topo, c.rigDeform, 2);
    extendWeightsToAux(dist, c.full, c.rigDeform);
    heat = generateHeatWeights(body, c.topo, c.rigDeform, 8.0, 60, 4.0);
    extendWeightsToAux(heat, c.full, c.rigDeform);
    SkinWeights mhCore = remapToRig(mh, c.rigDeform, c.rigCore);
    SkinWeights heatCore = remapToRig(heat, c.rigDeform, c.rigCore);
    struct WRow { const char* name; const SkinWeights* sw; const Rig* rig; };
    const std::vector<WRow> wrows = {
        {"MakeHuman default_weights.mhw (license PENDING) + deform rig", &mh, &c.rigDeform},
        {"PAE distance weights + deform rig", &dist, &c.rigDeform},
        {"PAE heat-diffusion weights + deform rig", &heat, &c.rigDeform},
        {"MakeHuman weights remapped to parents + core rig", &mhCore, &c.rigCore},
        {"PAE heat weights remapped to parents + core rig", &heatCore, &c.rigCore},
    };
    std::string wMd = "# Skin weights (generated)\n\n| Set | Bones | Mean influences (after Top-4) | Mass discarded by Top-4 | Unweighted verts | Generation | Dominant-bone agreement with MakeHuman set | Mean L1 vs MakeHuman set |\n|---|---:|---:|---:|---:|---|---:|---:|\n";
    for (const WRow& w : wrows) {
        const WeightStats s = weightStats(*w.sw, static_cast<int>(base.size()));
        const double agree = w.sw == &mh ? 1.0 : dominantBoneAgreement(mh, c.rigDeform, *w.sw, *w.rig);
        const double l1 = w.sw == &mh ? 0.0 : weightL1Difference(mh, c.rigDeform, *w.sw, *w.rig);
        wMd += fmt("| %s | %zu | %.3f | %.3f %% | %ld | %.1f ms | %.1f %% | %.3f |\n", w.name, w.rig->bones.size(), s.meanInfluences,
                   w.sw->massLostByCompression * 100.0, s.verticesWithoutWeight, w.sw->generationMs, agree * 100.0, l1);
        say(fmt("[weights] %-58s bones %3zu meanInf %.3f top4-loss %.3f%% unweighted %ld gen %7.1f ms agree %5.1f%% L1 %.3f", w.name,
                w.rig->bones.size(), s.meanInfluences, w.sw->massLostByCompression * 100.0, s.verticesWithoutWeight, w.sw->generationMs, agree * 100.0, l1));
    }
    wMd += fmt("\nMakeHuman set: %ld entries, index base detected as %d, %ld entries belong to facial bones that are not in the deform rig (dropped), mean influences before Top-4 %.3f.\n\nPAE generators (host, no external code): **distance** = inverse-square distance to bone segments, cut at one local bone radius (radius = median plain distance of the vertices closest to that bone), two Laplacian smoothing passes on the mesh graph, normalise, Top-4. **heat** = bone-heat diffusion `(I + tL)h = e` on the uniform mesh graph (t = 8, 60 Jacobi iterations, uniform edge weights, NOT cotangent), per-bone max normalisation, power 4, normalise, Top-4. Neither method is a bounded-biharmonic solve; that comparison is NOT RUN.\n",
               mh.entriesRead, mh.detectedIndexBase, mh.unknownBoneEntries, mh.meanInfluencesBeforeCompression);
    {
        const int bodyTotal = static_cast<int>(base.size());
        const long bodyAncestor = countFallback(mh, WeightFallback::KeptAncestor, bodyTotal), bodyNearest = countFallback(mh, WeightFallback::NearestBone, bodyTotal);
        const long allAncestor = countFallback(mh, WeightFallback::KeptAncestor), allNearest = countFallback(mh, WeightFallback::NearestBone);
        wMd += fmt("\n**Weight fallback (MakeHuman set, deterministic, host).** %ld body vertices end up without any influence because every one of their source weights sits on a facial bone that the deform rig does not keep. Rule `kept-ancestor`: each dropped bone is replaced by its nearest kept ancestor in the source hierarchy (all facial bones resolve to `head` here) and the masses are merged, Top-4, renormalised. Rule `nearest-bone`: a vertex with no usable source entry is bound to the nearest bone segment in the rest pose. Result: body %ld kept-ancestor + %ld nearest-bone, auxiliary ids %ld + %ld, %ld ids still unweighted; vertices that already had a kept source weight are not touched. The per-vertex rule is stored in the template (format 2). NOT changed: body vertices that carry both a kept and a facial-bone influence keep only the kept part, renormalised (the facial part is discarded).\n",
                    bodyAncestor + bodyNearest, bodyAncestor, bodyNearest, allAncestor - bodyAncestor, allNearest - bodyNearest,
                    static_cast<long>(weightStats(mh).verticesWithoutWeight));
        say(fmt("[weights] fallback: body %ld kept-ancestor + %ld nearest-bone, aux %ld + %ld, %ld ids unweighted", bodyAncestor, bodyNearest,
                allAncestor - bodyAncestor, allNearest - bodyNearest, static_cast<long>(weightStats(mh).verticesWithoutWeight)));
    }
    writeFile(reportDir + "/weights.md", wMd);

    // ------------------------------------------------------ 7. poses
    const std::vector<PoseDef> poses = {
        {"bind", {}, "head", false},
        {"shoulder-abduction-L", {{"upperarm01.L", D3{0, 0, 1}, 70.0}}, "wrist.L", false},
        {"elbow-flexion-L", {{"lowerarm01.L", D3{-1, 0, 0}, 90.0}}, "wrist.L", false},
        {"hip-flexion-L", {{"upperleg01.L", D3{-1, 0, 0}, 60.0}}, "lowerleg01.L", false},
        {"knee-flexion-L", {{"lowerleg01.L", D3{1, 0, 0}, 70.0}}, "foot.L", false},
        {"wrist-twist-L", {{"wrist.L", D3{}, 60.0}}, "finger3-3.L", false},
        {"ankle-plantarflexion-L", {{"foot.L", D3{1, 0, 0}, 25.0}}, "toe3-3.L", false},
        {"finger-curl-L", {{"finger1-1.L", D3{}, 50.0}, {"finger1-2.L", D3{}, 50.0}, {"finger2-1.L", D3{}, 50.0}, {"finger2-2.L", D3{}, 50.0},
                           {"finger3-1.L", D3{}, 50.0}, {"finger3-2.L", D3{}, 50.0}, {"finger4-1.L", D3{}, 50.0}, {"finger4-2.L", D3{}, 50.0},
                           {"finger5-1.L", D3{}, 50.0}, {"finger5-2.L", D3{}, 50.0}}, "finger3-3.L", true},
    };
    struct PoseRow { std::string pose, set; DeformationQuality q; double ms; D3 moved; bool probePresent; };
    std::vector<PoseRow> poseRows;
    for (const PoseDef& pose : poses) {
        for (const WRow& w : wrows) {
            const std::vector<BoneRotation> rot = resolvePose(*w.rig, pose);
            const double t0 = nowMs();
            const std::vector<Affine> globals = poseGlobals(*w.rig, rot);
            const std::vector<Affine> skin = skinMatrices(*w.rig, globals);
            // Skin the full surface (body + helpers), audit the body part.
            const std::vector<D3> posedFull = lbsSkin(c.full, *w.sw, skin);
            const std::vector<D3> posed(posedFull.begin(), posedFull.begin() + static_cast<std::ptrdiff_t>(base.size()));
            const double ms = nowMs() - t0;
            const int probe = w.rig->find(pose.probe);
            D3 moved;
            // A bone's rest head is moved by its SKIN matrix, never by its global matrix.
            if (probe >= 0) moved = skin[static_cast<size_t>(probe)].apply(w.rig->bones[static_cast<size_t>(probe)].head) - w.rig->bones[static_cast<size_t>(probe)].head;
            poseRows.push_back({pose.name, w.name, compareSurfaces(body, posed, c.topo), ms, moved, probe >= 0});
        }
    }
    std::string pMd = "# LBS poses (generated)\n\nHost linear blend skinning on the base body. Rotation axes are given in the rest world frame (+Y up, +Z forward, +X = character's left). Columns: folded faces (normal flip vs rest), 99th-percentile edge stretch/squash, worst edge ratio, volume ratio, skinning time, displacement of the probe joint. The core rig has no finger or toe bones, so its finger/ankle rows are effectively a bind pose and only prove that the remap is well-formed.\n\n| Pose | Weight set | Folded faces | Edge p99 | Edge min / max | Volume ratio | Skinning | Probe joint displacement (x, y, z) |\n|---|---|---:|---:|---|---:|---:|---|\n";
    for (const PoseRow& r : poseRows) {
        const std::string disp = r.probePresent ? fmt("%+.3f / %+.3f / %+.3f", r.moved.x, r.moved.y, r.moved.z) : std::string("probe bone absent");
        pMd += fmt("| %s | %s | %ld | %.3f | %.3f / %.3f | %.4f | %.1f ms | %s |\n", r.pose.c_str(), r.set.c_str(), r.q.flippedFaces,
                   r.q.edgeRatioP99, r.q.minEdgeRatio, r.q.maxEdgeRatio, r.q.volumeRatio, r.ms, disp.c_str());
        if (r.pose != "bind")
            say(fmt("[pose] %-26s %-58s flips %3ld edgeP99 %.3f vol %.4f probe(%+.3f %+.3f %+.3f)", r.pose.c_str(), r.set.c_str(), r.q.flippedFaces,
                    r.q.edgeRatioP99, r.q.volumeRatio, r.moved.x, r.moved.y, r.moved.z));
    }
    pMd += "\nNot measured: self-intersection (shoulder/axilla, hip/groin, knee), dual-quaternion skinning, pose correctives, twist propagation between twist bones. Joint-centre displacement is a kinematic check, not a visual one.\n";
    writeFile(reportDir + "/poses.md", pMd);

    // ------------------------------------------------------ 8. template
    std::vector<TemplateShapeTarget> ttargets;
    for (const ShapeParam& p : c.params) {
        TemplateShapeTarget t;
        t.id = p.key;
        t.name = p.key;
        t.region = p.expectedRegions;
        t.relPath = p.incr.relPath;
        t.sha256 = p.incr.sha256;
        t.side = p.incrFiles.size() == 2 ? 3 : 0;
        t.vertex = p.incr.vertex;
        t.delta = p.incr.delta;
        ttargets.push_back(t);
        TemplateShapeTarget d = t;
        d.id = p.key + "-";
        d.relPath = p.decr.relPath;
        d.sha256 = p.decr.sha256;
        d.vertex = p.decr.vertex;
        d.delta = p.decr.delta;
        ttargets.push_back(d);
    }
    const double tTemplate0 = nowMs();
    HumanTemplate t = buildTemplate(c, c.rigDeform, mh, ttargets, commit, files);
    const std::string bytes = serializeTemplate(t);
    const std::string templatePath = templateDir + "/pae-human-template-mh-a8bc2d54.paht";
    writeFile(templatePath, bytes);
    HumanTemplate back;
    const bool roundTrip = parseTemplate(bytes, back, error) && serializeTemplate(back) == bytes;
    const double templateMs = nowMs() - tTemplate0;
    const std::string templateSha = sha256Hex(std::vector<uint8_t>(bytes.begin(), bytes.end()));
    const std::string objPath = exportDir + "/pae-human-base-triangulated.obj";
    writeTriangulatedObj(objPath, body);
    say(fmt("[template] %zu bytes sha256 %s roundtrip=%s | landmarks %zu (joints + 6 derived surface) | targets %zu | export %s", bytes.size(),
            templateSha.c_str(), roundTrip ? "byte-identical" : "FAILED", t.landmarks.size(), ttargets.size(), objPath.c_str()));

    // ------------------------------------------------------ 9. images
    std::vector<Camera> cameras = protocolCameras(256, 512);
    // One frame per view shared by the base and the strongest variant.
    {
        std::vector<const std::vector<D3>*> positionSets = {&base, &combined};
        fitSharedFrames(cameras, positionSets);
    }
    // Pointers into `variants` are kept in RenderSurface during a shoot only,
    // and the reserve below makes sure the outer vector never re-allocates.
    std::vector<std::vector<D3>> variants;
    variants.reserve(80);
    variants.push_back(combined);
    std::string imageMd = "# Evidence images (generated by the host software renderer)\n\nCamera: PAE CameraProtocol::fixedViews() (7 views) plus `side-right`; one shared orthographic frame per view over base and combined variants. Clay shading and light are PAE's ClayRenderer formula. This is NOT the Android GLES3 renderer.\n\n| File | Caption |\n|---|---|\n";
    int imageCount = 0;
    if (images) {
        auto shoot = [&](const std::string& file, const std::string& caption, const RenderSurface& s, int cam, ShadeMode mode, bool wire) {
            const Rgb img = renderSurface(s, cameras[static_cast<size_t>(cam)], mode, wire);
            if (writePngFile(imageDir + "/" + file, img)) {
                ++imageCount;
                imageMd += fmt("| `%s` | %s |\n", file.c_str(), caption.c_str());
            } else
                say("[image] FAILED to write " + file);
        };
        const RenderSurface baseSurface{&body, &base, &c.regions, &mh, &c.rigDeform};
        const char* views[] = {"front", "front-45-left", "side-left", "side-left-30up", "back", "back-45-right", "front-30up", "side-right"};
        for (int v = 0; v < 8; ++v)
            shoot(fmt("base-clay-%s.png", views[v]), fmt("base body, clay, %s view (PAE protocol view)", views[v]), baseSurface, v, ShadeMode::Clay, false);
        shoot("base-wire-front.png", "base body, clay + wireframe overlay (quad edges), front", baseSurface, 0, ShadeMode::Clay, true);
        shoot("base-wire-front-45-left.png", "base body, clay + wireframe overlay, front-45-left", baseSurface, 1, ShadeMode::Clay, true);
        shoot("base-normal-front.png", "base body, view-space normals, front", baseSurface, 0, ShadeMode::ViewNormal, false);
        shoot("base-regions-front.png", "base body, PAE anatomical region labels (heuristic nearest-bone)", baseSurface, 0, ShadeMode::RegionColor, false);
        shoot("weights-mh-front.png", "MakeHuman CC0 weights: colour = dominant bone, brightness = its weight, front", baseSurface, 0, ShadeMode::WeightHeat, false);
        shoot("weights-mh-back.png", "MakeHuman CC0 weights, back", baseSurface, 4, ShadeMode::WeightHeat, false);
        shoot("weights-pae-heat-front.png", "PAE heat-diffusion weights, front", RenderSurface{&body, &base, &c.regions, &heat, &c.rigDeform}, 0, ShadeMode::WeightHeat, false);
        shoot("weights-pae-distance-front.png", "PAE distance weights, front", RenderSurface{&body, &base, &c.regions, &dist, &c.rigDeform}, 0, ShadeMode::WeightHeat, false);
        int pi = 0;
        for (const ShapeParam& p : c.params) {
            std::vector<D3> inc, dec;
            applyToBody(c, {{&p.incr, 1.0}}, inc);
            applyToBody(c, {{&p.decr, 1.0}}, dec);
            variants.push_back(inc);
            const size_t ii = variants.size() - 1;
            variants.push_back(dec);
            const size_t di = variants.size() - 1;
            const RenderSurface si{&body, &variants[ii], &c.regions, nullptr, nullptr}, sd{&body, &variants[di], &c.regions, nullptr, nullptr};
            shoot(fmt("target-%02d-%s-incr.png", pi, p.key.c_str()), fmt("`%s` = +1.0, front", p.key.c_str()), si, 0, ShadeMode::Clay, false);
            shoot(fmt("target-%02d-%s-decr.png", pi, p.key.c_str()), fmt("`%s` = -1.0 (decr target at +1.0), front", p.key.c_str()), sd, 0, ShadeMode::Clay, false);
            ++pi;
        }
        const RenderSurface combinedSurface{&body, &variants[0], &c.regions, nullptr, nullptr};
        shoot("target-all-combined-front.png", "all nine parameters at +1.0, front", combinedSurface, 0, ShadeMode::Clay, false);
        shoot("target-all-combined-front-45-left.png", "all nine parameters at +1.0, front-45-left", combinedSurface, 1, ShadeMode::Clay, false);
        const WRow* mhRow = &wrows[0];
        const WRow* heatRow = &wrows[2];
        const WRow* coreRow = &wrows[3];
        for (const PoseDef& pose : poses) {
            if (pose.name == "bind") continue;
            struct S { const WRow* w; const char* tag; };
            for (const S& s : {S{mhRow, "mh"}, S{heatRow, "paeheat"}, S{coreRow, "mhcore20"}}) {
                const std::vector<Affine> g = poseGlobals(*s.w->rig, resolvePose(*s.w->rig, pose));
                const std::vector<D3> posedFull = lbsSkin(c.full, *s.w->sw, skinMatrices(*s.w->rig, g));
                variants.push_back(std::vector<D3>(posedFull.begin(), posedFull.begin() + static_cast<std::ptrdiff_t>(base.size())));
                const RenderSurface ps{&body, &variants.back(), &c.regions, nullptr, nullptr};
                shoot(fmt("pose-%s-%s-front-45-left.png", pose.name.c_str(), s.tag), fmt("pose %s, weights %s, front-45-left", pose.name.c_str(), s.w->name), ps, 1, ShadeMode::Clay, false);
                if (pose.name == "elbow-flexion-L")
                    shoot(fmt("pose-%s-%s-side-left.png", pose.name.c_str(), s.tag), fmt("pose %s, weights %s, side-left", pose.name.c_str(), s.w->name), ps, 2, ShadeMode::Clay, false);
            }
        }
        // Anatomy close-ups: wireframe over clay so the edge flow of the
        // shoulder, axilla, hip, face, hand and foot can actually be looked at.
        auto jointOf = [&](const char* bone, bool head) {
            const int b = c.rigDeform.find(bone);
            return b >= 0 ? (head ? c.rigDeform.bones[static_cast<size_t>(b)].head : c.rigDeform.bones[static_cast<size_t>(b)].tail) : D3{};
        };
        auto regionBox = [&](Region region, int sideSign, D3& lo, D3& hi) {
            lo = D3{1e9, 1e9, 1e9};
            hi = D3{-1e9, -1e9, -1e9};
            for (size_t v = 0; v < base.size(); ++v) {
                if (c.regions[v] != region || (sideSign != 0 && base[v].x * sideSign <= 0.0)) continue;
                lo.x = std::min(lo.x, base[v].x); lo.y = std::min(lo.y, base[v].y); lo.z = std::min(lo.z, base[v].z);
                hi.x = std::max(hi.x, base[v].x); hi.y = std::max(hi.y, base[v].y); hi.z = std::max(hi.z, base[v].z);
            }
        };
        auto around = [&](const D3& centre, double hx, double hy, double hz, D3& lo, D3& hi) {
            lo = centre - D3{hx, hy, hz};
            hi = centre + D3{hx, hy, hz};
        };
        struct Closeup { std::string name; D3 lo, hi; std::vector<std::pair<double, double>> views; };
        std::vector<Closeup> closeups;
        {
            D3 lo, hi;
            around(jointOf("upperarm01.L", true), 0.13, 0.11, 0.13, lo, hi);
            closeups.push_back({"shoulder-L", lo, hi, {{0, 0}, {45, 0}, {90, 0}, {0, 60}}});
            around(jointOf("upperarm01.L", true) + D3{0.0, -0.075, 0.0}, 0.10, 0.055, 0.10, lo, hi);
            closeups.push_back({"axilla-L", lo, hi, {{0, 0}, {20, -50}, {90, -20}}});
            around(jointOf("upperleg01.L", true) + D3{-0.02, 0.02, 0.02}, 0.12, 0.12, 0.11, lo, hi);
            closeups.push_back({"hip-groin-L", lo, hi, {{0, 0}, {0, -30}, {90, 0}}});
            regionBox(Region::Head, 0, lo, hi);
            lo.z = std::max(lo.z, -0.06);  // keep the face, drop the back of the skull
            hi.z = std::min(hi.z, 0.17);
            closeups.push_back({"face", lo, hi, {{0, 0}, {90, 0}, {45, 0}}});
            regionBox(Region::Hand, +1, lo, hi);
            closeups.push_back({"hand-L", lo, hi, {{0, 0}, {45, 0}, {90, 0}, {225, 0}}});
            regionBox(Region::Foot, +1, lo, hi);
            closeups.push_back({"foot-L", lo, hi, {{90, 0}, {45, 0}, {0, 70}}});
            around(jointOf("lowerarm01.L", true), 0.07, 0.10, 0.07, lo, hi);
            closeups.push_back({"elbow-L", lo, hi, {{90, 0}, {45, 0}}});
            around(jointOf("lowerleg01.L", true), 0.08, 0.11, 0.08, lo, hi);
            closeups.push_back({"knee-L", lo, hi, {{0, 0}, {90, 0}}});
        }
        for (const Closeup& cu : closeups) {
            for (size_t vi = 0; vi < cu.views.size(); ++vi) {
                Camera camera = makeCamera(fmt("%s-az%d-el%d", cu.name.c_str(), static_cast<int>(cu.views[vi].first),
                                                static_cast<int>(cu.views[vi].second)), cu.views[vi].first, cu.views[vi].second, 480, 480);
                fitCameraToBox(camera, cu.lo, cu.hi);
                const Rgb img = renderSurface(baseSurface, camera, ShadeMode::Clay, true);
                const std::string file = fmt("closeup-%s-%d.png", cu.name.c_str(), static_cast<int>(vi));
                if (writePngFile(imageDir + "/" + file, img)) {
                    ++imageCount;
                    imageMd += fmt("| `%s` | close-up `%s`, wireframe over clay, azimuth %.0f / elevation %.0f, box x %.3f..%.3f y %.3f..%.3f z %.3f..%.3f m |\n",
                                   file.c_str(), cu.name.c_str(), cu.views[vi].first, cu.views[vi].second, cu.lo.x, cu.hi.x, cu.lo.y, cu.hi.y, cu.lo.z, cu.hi.z);
                }
            }
        }
        const double iou = claySilhouetteIoUWithPae(body, cameras[0]);
        imageMd += fmt("\nCross-check: this rasterizer vs PAE ClayRenderer::renderClayView on the base body, front view: silhouette IoU = %.4f.\n", iou);
        say(fmt("[images] %d PNG files written to %s | PAE clay cross-check IoU %.4f", imageCount, imageDir.c_str(), iou));
    } else {
        say("[images] skipped (--no-images)");
    }
    imageMd += fmt("\nGenerated images: %d.\n", imageCount);
    writeFile(reportDir + "/images.md", imageMd);

    // ------------------------------------------------------ 10. metrics
    std::string md = "# Host-only proof metrics (generated by pae_ht_pipeline)\n\n";
    md += fmt("- Run: %s\n- Source: makehumancommunity/makehuman @ `%s`\n- Tool: pae_ht_pipeline (C++17 host, `%s`)\n- Total runtime: %.0f ms\n\n",
              utcNow().c_str(), commit.c_str(), "pae-ht-proof 0.1", nowMs() - tStart);
    md += "## Base measurements (metres)\n\n| Stature | Bideltoid | Chest W x D | Waist W x D | Hip | Upper arm | Forearm | Thigh | Shank |\n|---|---|---|---|---|---|---|---|---|\n";
    md += fmt("| %.4f | %.4f | %.4f x %.4f | %.4f x %.4f | %.4f | %.4f | %.4f | %.4f | %.4f |\n\n", baseM.stature, baseM.bideltoidWidth, baseM.chestWidth,
              baseM.chestDepth, baseM.waistWidth, baseM.waistDepth, baseM.hipWidth, baseM.upperArmLength, baseM.forearmLength, baseM.thighLength, baseM.shankLength);
    md += "Limb ratios to stature: " + fmt("upper arm %.3f, forearm %.3f, thigh %.3f, shank %.3f.\n\n", baseM.upperArmLength / baseM.stature,
              baseM.forearmLength / baseM.stature, baseM.thighLength / baseM.stature, baseM.shankLength / baseM.stature);
    md += "## Timings (host, single thread)\n\n| Step | ms |\n|---|---:|\n";
    md += fmt("| Load OBJ + topology + rig + region labels | %.1f |\n| Nine parameters, apply + measure + quality | %.1f |\n", loadMs, targetTotalMs);
    md += fmt("| Distance weights (%zu bones) | %.1f |\n| Heat weights (%zu bones) | %.1f |\n", c.rigDeform.bones.size(), dist.generationMs, c.rigDeform.bones.size(), heat.generationMs);
    double lbsTotal = 0.0;
    for (const PoseRow& r : poseRows) lbsTotal += r.ms;
    md += fmt("| LBS skinning, %zu pose x set combinations (incl. quality audit) | %.1f |\n| Template serialize + parse + re-serialize | %.1f |\n\n", poseRows.size(), lbsTotal, templateMs);
    md += "## Outputs\n\n- `report/topology-audit.md`, `report/shape-targets.md`, `report/rig.md`, `report/weights.md`, `report/poses.md`, `report/images.md`\n- `provenance/asset-manifest.md`\n- `template/pae-human-template-mh-a8bc2d54.paht` (" + std::to_string(bytes.size()) + " bytes, sha256 `" + templateSha + "`, round trip " + (roundTrip ? "byte-identical" : "FAILED") + ")\n- `export/pae-human-base-triangulated.obj`\n";
    writeFile(reportDir + "/metrics.md", md);
    writeFile(outDir + "/pipeline.log", gLog);
    say(fmt("[done] %.0f ms -> %s", nowMs() - tStart, outDir.c_str()));
    return roundTrip ? 0 : 1;
}

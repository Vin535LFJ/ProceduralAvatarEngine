struct PoseDef {
    std::string name;
    std::vector<std::tuple<std::string, D3, double>> rotations;  // bone, rest-world axis, degrees; zero axis -> bone axis
    std::string probe;      // joint whose displacement is reported
    bool palmCurl = false;  // choose the sign that curls towards -X (palm faces the thigh)
};

std::vector<BoneRotation> resolvePose(const Rig& rig, const PoseDef& pose) {
    std::vector<BoneRotation> out;
    for (const auto& r : pose.rotations) {
        const int b = rig.find(std::get<0>(r));
        if (b < 0) continue;
        D3 axis = std::get<1>(r);
        double angle = std::get<2>(r);
        if (axis.lengthSq() < 0.5) axis = (rig.bones[static_cast<size_t>(b)].tail - rig.bones[static_cast<size_t>(b)].head).normalized();
        if (pose.palmCurl) {
            // Pick the sign whose rotation moves the bone tail towards -X.
            const RigBone& bone = rig.bones[static_cast<size_t>(b)];
            const Affine test = Affine::translation(bone.head) * Affine::rotation(axis, angle * 3.14159265358979323846 / 180.0);
            if (test.apply(bone.tail).x - bone.tail.x > 0.0) angle = -angle;
        }
        out.push_back({b, axis, angle});
    }
    return out;
}

